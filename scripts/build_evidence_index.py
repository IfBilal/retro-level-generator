"""Write evidence/audit/INDEX.md: what every file under evidence/audit/ proves.  python scripts/build_evidence_index.py

Explain-me:
  What: walks evidence/audit/<UTC timestamp>/ and describes each file by name pattern (the browser audit scripts name their outputs systematically), then
        adds the pointers to the audit runs under reports/audit/.  A file with no matching pattern is listed as "unclassified" so nothing is silently undocumented.
  In/Out: evidence/audit/** -> evidence/audit/INDEX.md.  Previous: scripts/audit_browser*.py, audit_visual_check.py.  Next: reports/audit/AUDIT_REPORT.md links here.
  Try: python scripts/build_evidence_index.py && grep -c unclassified evidence/audit/INDEX.md
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "evidence/audit"

PATTERNS = [
    (r"deployed_before_fix_DEFECT_dice\d+\.png", "the DEPLOYED app (before the fix) showing StreamlitWidgetAlreadyInstantiatedError after repeated Dice clicks (defect D1, reproduced in production)"),
    (r"browser_deployed_before_fix\.json", "browser audit of the deployed app before the fix: the Dice defects are listed in 'defects'"),
    (r".*_01_loaded\.png", "the page right after loading"),
    (r".*_02_generated\.png", "the page after Generate & Play (badge, notices, embedded game, tabs)"),
    (r"browser_.*\.json", "browser audit result: steps, console errors, failed requests, defects (empty = none)"),
    (r"states_vp(\d+x\d+)_loaded\.png", "viewport check, page loaded (no horizontal overflow, Generate reachable)"),
    (r"states_vp(\d+x\d+)_generated\.png", "viewport check, after generating (full page)"),
    (r"states_state_edited_not_regenerated\.png", "state check: the sentence was edited without regenerating -> the old level is labelled as an earlier sentence"),
    (r"states_state_double_click\.png", "state check: Generate clicked twice while generating"),
    (r"states_state_reloaded\.png", "state check: page reloaded mid-generation, app usable again"),
    (r"states_state_nav_(Gallery|About|Studio)\.png", "state check: navigation to the page named in the file"),
    (r"states_state_gallery_pick\.png", "state check: the Gallery level picker"),
    (r"states_state_tab2\.png", "state check: second browser tab generating at the same time"),
    (r"states_seed_seed_done\.png", "seed field edge cases, step buttons, seed shown = seed used, CFG slider by keyboard"),
    (r"states_kbd_keyboard\.png", "keyboard-only use: Tab reaches the button, Enter generates"),
    (r"states_offline_offline\.png", "every non-local request blocked: the app and the bundled game still work"),
    (r"states_offline_blocked_requests\.txt", "the external requests that were blocked ('(none)' = the app made none)"),
    (r"states_play_before\.png|states_play_after\.png", "the game canvas before / after pressing right + jump (the frame must change)"),
    (r"states_equality\.json", "the captions shown in the 'what the model will understand' panel vs the captions recorded in the level, and the per-window captions actually sent to the model"),
    (r"visual_check_(.+)\.png", "contact sheet of generated levels with the counter's result in each title: check the counts by eye"),
    (r"visual_check_(.+)\.json", "what the contact sheet shows (prompt, seed, checks, all objects found)"),
    (r"states_.*\.png", "browser state screenshot"),
    (r"browser_states\.json", "pass/fail of every browser state check (viewports, state, seed, keyboard, offline, play, equality)"),
]


def describe(name):
    for pat, text in PATTERNS:
        if re.fullmatch(pat, name):
            return text
    return "unclassified"


def main():
    lines = ["# What each file under `evidence/audit/` proves", "",
             ("Generated by `scripts/build_evidence_index.py`.  Each directory is one browser/visual audit session (UTC timestamp).  The adherence runs themselves live in "
              "`reports/audit/<run>/` (`rows.jsonl` = every level, `results.json`, `RESULTS.md`); `reports/audit/AUDIT_REPORT.md` cites both."), ""]
    for d in sorted(EV.glob("2*")):
        files = sorted(p for p in d.iterdir() if p.is_file())
        note = ""
        bs = d / "browser_states.json"
        if bs.exists():
            rs = json.loads(bs.read_text(encoding="utf-8"))
            note = f" - state checks: {sum(1 for r in rs if r['pass'])}/{len(rs)} pass"
        lines += [f"## {d.name}{note}", "", "| file | what it proves |", "|---|---|"]
        lines += [f"| `{p.name}` | {describe(p.name)} |" for p in files]
        lines.append("")
    lines += ["## Audit runs (`reports/audit/`)", "",
              "| run | what it is |", "|---|---|",
              "| `baseline`, `baseline_adv`, `baseline_full` | the UNMODIFIED code (git da3a89d): prompts, input-safety re-run with the corrected check, and the merged set used as the baseline |",
              "| `roundC_baseline_seeds`, `roundD_fresh2_seeds`, `roundD_fresh2_prompts` | the two final consecutive rounds (numbers of record) |",
              "| `roundA`, `roundB_fresh_seeds`, `roundB_fresh_prompts` | the earlier confirmation attempt; round B's single miss led to the staircase fix |",
              "| `round1_partial_counts`, `round2_noncount`, `round3`, `round4`, `round4_adv`, `round5` | development rounds (history) |",
              "| `cloud_cpu` | cloud profile: `T2M_PROFILE=cloud`, CPU, 45 s guard |",
              "| `variety.*`, `NOTES_towers.md`, `window_exactness.json`, `DATAFLOW.md`, `TARGETS.md` | contrarian checks, the data-flow study and the targets written before measuring |", ""]
    (EV / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote evidence/audit/INDEX.md;", sum(1 for ln in lines if "unclassified" in ln), "unclassified file(s)")


if __name__ == "__main__":
    main()
